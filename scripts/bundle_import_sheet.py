#!/usr/bin/env python3
"""Build a single-file copy of the import-sheet Edge Function for pasting into the Supabase dashboard.

The function lives in supabase/functions/import-sheet/ as five modules. The CLI deploys them as is
(`supabase functions deploy import-sheet`). Without the CLI, paste supabase/paste/import-sheet.ts
(written by this script) into the dashboard's import-sheet editor and deploy.

  python3 scripts/bundle_import_sheet.py          # write the paste file
  python3 scripts/bundle_import_sheet.py --check  # exit 1 if the paste file is out of date
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "supabase" / "functions" / "import-sheet"
OUT = ROOT / "supabase" / "paste" / "import-sheet.ts"
# Dependency order: each module only uses the ones before it.
MODULES = ["chord_net.ts", "layout.ts", "pdf.ts", "ug.ts", "index.ts"]

IMPORT_RE = re.compile(r'^import\s[\s\S]*?\sfrom\s+"([^"]+)";\s*$', re.M)


def build() -> str:
    external: list[str] = []
    parts: list[str] = []
    for name in MODULES:
        code = (SRC / name).read_text(encoding="utf-8")
        for m in IMPORT_RE.finditer(code):
            if not m.group(1).startswith("./") and m.group(0).strip() not in external:
                external.append(m.group(0).strip())
        code = IMPORT_RE.sub("", code)
        # Everything shares one file, so nothing needs exporting.
        code = re.sub(r"^export\s+(?=(?:async\s+)?function\b|const\b|let\b|type\b|class\b|interface\b)", "", code, flags=re.M)
        if re.search(r"^export\b", code, re.M):
            raise SystemExit(f"{name}: an export form this script doesn't handle")
        parts.append(f"// ===== {name} =====\n{code.strip()}\n")
    head = (
        "// GENERATED by scripts/bundle_import_sheet.py: do not edit.\n"
        "// Edit the modules in supabase/functions/import-sheet/, then run the script again.\n"
        "// Paste this whole file into the Supabase dashboard (Edge Functions > import-sheet) and deploy.\n\n"
    )
    return head + "\n".join(external) + "\n\n" + "\n".join(parts)


def main():
    text = build()
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print("supabase/paste/import-sheet.ts is out of date: run python3 scripts/bundle_import_sheet.py")
            sys.exit(1)
        print("supabase/paste/import-sheet.ts is up to date.")
        return
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8")
    print(f"Wrote {OUT.relative_to(ROOT)} ({len(text.splitlines())} lines)")


if __name__ == "__main__":
    main()
